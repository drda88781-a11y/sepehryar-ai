    @classmethod
    def find_catalog_match(cls, query: str, q_norm: str) -> Optional[Any]:
        """
        Dynamically matches any form from the 619 extracted forms in ui_catalog.json,
        delivering exact menu paths, shortcuts, screenshots, and double-entry accounting entries.
        """
        import json
        from pathlib import Path
        from app.agent.cognitive_engine import SepehryarCognitiveResponse, CognitiveThoughtStep

        catalog_path = Path("D:/ai app/knowledge_base/manuals/images/ui_catalog.json")
        if not catalog_path.exists():
            return None

        try:
            with open(catalog_path, "r", encoding="utf-8") as f:
                catalog = json.load(f)
        except Exception:
            return None

        # Guard: Let architectural cognitive copilot handle migration and personcod topics
        if any(w in q_norm for w in ["مهاجرت", "باران", "هلو", "دشت", "سپیدار", "سپیدز", "تبدیل دیتابیس", "کانورت"]):
            return None
        if any(w in q_norm for w in ["مشتری جدید ثبت کنم", "شخص جدید ثبت کنم", "حسابش رو وصل"]):
            return None

        stop_words = {"چطور", "چگونه", "نحوه", "یاد", "آموزش", "فرم", "منو", "عکس", "تصویر", "سپهریار", "نرم", "افزار", "چیست", "کجاست", "روش", "کار", "با", "های", "ها"}
        words = [w for w in q_norm.split() if len(w) > 2 and w not in stop_words]
        if not words:
            return None

        best_item = None
        best_score = 0

        for item_id, item in catalog.items():
            title = item.get("title", "").strip()
            if len(title) <= 3 or title in ["سپهریار", "سیستم", "عملیات"]:
                continue
            t_norm = title.replace("‌", " ").replace("ي", "ی").replace("ك", "ک").lower()
            score = 0
            if q_norm in t_norm:
                score += 15
            if t_norm in q_norm and len(t_norm) > 4:
                score += 10
            for w in words:
                if w in t_norm:
                    score += 4

            if score > best_score and score >= 4:
                best_score = score
                best_item = item

        if not best_item:
            return None

        title = best_item.get("title", "")
        subsystem = best_item.get("subsystem", "نرم‌افزار حسابداری سپهریار")
        shortcut = best_item.get("shortcut", "")
